const { it } = require('node:test');
const assert = require('node:assert/strict');
const THREE = require('three');
const { load } = require('../support/load-ts.cjs');
const config = { LAYER_STRUCTURE: 28, LAYER_DOORS: 7, LAYER_WALL_STRUCTURE: 8, LAYER_FLOOR_COVERINGS: 9 };
const { applyMagazineCut } = load('src/features/scene/photo/clipGeometryY.ts', { three: THREE, '@config': config });

it('keeps high closet shelves and contents visible while cutting the doors at 135 cm', () => {
  const root = new THREE.Group();
  const closet = new THREE.Group();
  closet.userData.magazineCut = false;
  root.add(closet);
  const shelf = new THREE.Mesh(new THREE.BoxGeometry(60, 3, 50));
  shelf.position.y = 180;
  shelf.layers.set(config.LAYER_DOORS);
  const contents = new THREE.Mesh(new THREE.BoxGeometry(10, 20, 10));
  contents.position.y = 192;
  const door = new THREE.Group();
  door.userData.magazineCut = true;
  const panel = new THREE.Mesh(new THREE.BoxGeometry(60, 250, 2));
  panel.position.y = 125;
  const handle = new THREE.Mesh(new THREE.BoxGeometry(2, 10, 2));
  handle.position.y = 180;
  door.add(panel, handle);
  closet.add(shelf, contents, door);
  const originalShelf = shelf.geometry;
  const originalPanel = panel.geometry;
  const geometry = new Map(), hidden = [];
  applyMagazineCut(root, 135, geometry, hidden);
  assert.equal(shelf.visible, true);
  assert.equal(shelf.geometry, originalShelf);
  assert.equal(contents.visible, true);
  assert.equal(panel.visible, true);
  assert.notEqual(panel.geometry, originalPanel);
  assert.equal(new THREE.Box3().setFromObject(panel).max.y, 135);
  assert.equal(handle.visible, false);
  assert.deepEqual(hidden, [handle]);
  assert.equal(geometry.get(panel), originalPanel);
});
