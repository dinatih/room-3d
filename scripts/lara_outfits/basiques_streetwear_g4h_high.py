def _assign_uvs_and_mats(bm: bmesh.types.BMesh, uv_layer, trim_faces: set, lining_faces: set, has_arms: bool):
    for f in bm.faces:
        f.smooth = True
        if f in lining_faces:
            f.material_index = 2
        elif f in trim_faces:
            f.material_index = 1
        else:
            f.material_index = 0
        for loop in f.loops:
            co = loop.vert.co
            if has_arms and abs(co.x) > 0.165 and co.z > 1.30:
                ang = math.atan2(co.z - 1.42, co.y)
                loop[uv_layer].uv = ((ang / (2.0 * math.pi) + 0.5) * 1.4, abs(co.x) * 2.2)
            else:
                cx = 0.068 if (co.z < 0.78 and co.x > 0.015) else (-0.068 if (co.z < 0.78 and co.x < -0.015) else 0.0)
                ang = math.atan2(co.y, co.x - cx)
                loop[uv_layer].uv = ((ang / (2.0 * math.pi) + 0.5) * 1.8, co.z * 2.2)


def _finalize_hoodie_mesh(
    name: str,
    bm: bmesh.types.BMesh,
    uv_layer,
    trim_faces: set,
    lining_faces: set,
    pin_verts: set,
    mats: dict,
    *,
    has_arms: bool,
    gravity: float,
    z_zip_bot: float,
    z_zip_top: float,
    pocket_z_range: tuple[float, float] | None,
    is_skirt: bool,
    armature,
    rel_out_path: str,
):
    _assign_uvs_and_mats(bm, uv_layer, trim_faces, lining_faces, has_arms)
    _orient_mesh_islands_outward(bm)
    bm.verts.index_update()
    pin_idx = {v.index for v in pin_verts if v.is_valid}

    mesh = bpy.data.meshes.new(name)
    bm.to_mesh(mesh)
    bm.free()

    obj = bpy.data.objects.new(name, mesh)
    bpy.context.scene.collection.objects.link(obj)
    obj.data.materials.append(mats["fleece"])
    obj.data.materials.append(mats["rib"])
    obj.data.materials.append(mats["lining"])

    fit_cloth_sim(obj, pin_idx, frames=16, mass=0.24, tension=34.0, compression=34.0, shear=18.0, bending=2.0, gravity=gravity)

    det = build_front_zipper_and_pockets(
        f"{name}_details",
        obj,
        z_zip_bot=z_zip_bot,
        z_zip_top=z_zip_top,
        pocket_z_range=pocket_z_range,
        mat_main=mats["fleece"],
        mat_trim=mats["rib"],
        mat_rail=mats["zip_plastic_red"],
        mat_metal=mats["zip_metal_red"],
    )
    join_objects(obj, [det])
    finalize_and_export(obj, armature, rel_out_path, has_arms=has_arms, is_skirt=is_skirt, breast_atten=0.45)
    bpy.data.objects.remove(obj, do_unlink=True)


def generate_basiques_streetwear(bvhs, mats, armature, only_ids: set[str] | None = None):
    """Generate all 6 GLBs covering Chart 03 · Streetwear & Hoodies."""
    def _want(oid: str) -> bool:
        return only_ids is None or oid in only_ids

    specs = [
        ("street-jumpsuit-hoodie", True),
        ("street-hoodie-sleeveless", False),
        ("street-hoodie-crop-long", True),
        ("street-hoodie-crop-sleeveless", False),
        ("street-dress-hoodie-long", True),
        ("street-dress-hoodie-sleeveless", False),
    ]
    if not any(_want(f"{sid}-{ID_SUFFIX}") for sid, _ in specs):
        return

    # Sleeveless items use sleeveless collider (clean armholes), sleeved items use full collider
    need_sleeveless = any(_want(f"{sid}-{ID_SUFFIX}") for sid, has_sl in specs if not has_sl)
    need_sleeved = any(_want(f"{sid}-{ID_SUFFIX}") for sid, has_sl in specs if has_sl)

    if need_sleeved:
        col_full, _, crotch_z, _ = build_body_collider(include_arms=True, clearance_outer=0.0025)

        # 1. Combinaison streetwear (Hooded lounge jumpsuit)
        oid = f"street-jumpsuit-hoodie-{ID_SUFFIX}"
        if _want(oid):
            bm = bmesh.new()
            uv = bm.loops.layers.uv.new("UVMap")
            pins, trim, lining = set(), set(), set()

            def _jump_ease(z, ang, side, zi, n):
                if z <= 0.195:
                    return 0.0072, z
                t_mid = math.sin(min(1.0, max(0.0, (z - 0.195) / (crotch_z - 0.195))) * math.pi)
                return 0.0125 + 0.0080 * t_mid, z

            w_ring, z_w = append_pants_quads(
                bm, bvhs, crotch_z, z_hem=0.145, z_waist=1.060,
                leg_ease_fn=_jump_ease,
                pelvis_ease_fn=lambda z, th: 0.0135,
                pin_verts=pins, trim_faces=trim, cuff_z_band=0.050, waist_z_band=0.0, pin_hem=True,
            )
            pins.update(w_ring)
            grid, _ = append_bodice_quads(
                bm, bvhs, z_w, w_ring, "long", "hood_collar",
                extra_ease=0.0095, pin_verts=pins, trim_faces=trim, hem_trim_h=0.0, cuff_trim=True,
            )
            append_hood_to_collar(bm, bvhs, grid[-1], pins, lining, narrow_shoulders=False)
            _finalize_hoodie_mesh(
                f"lara_street_jumpsuit_hoodie_{FILE_SUFFIX}", bm, uv, trim, lining, pins, mats,
                has_arms=True, gravity=0.18, z_zip_bot=0.945, z_zip_top=1.466, pocket_z_range=(1.035, 1.180),
                is_skirt=False, armature=armature, rel_out_path=f"streetwear/lara_street_jumpsuit_hoodie_{FILE_SUFFIX}.glb",
            )

        # 3. Hoodie zippé court à manches longues
        oid = f"street-hoodie-crop-long-{ID_SUFFIX}"
        if _want(oid):
            bm = bmesh.new()
            uv = bm.loops.layers.uv.new("UVMap")
            pins, trim, lining = set(), set(), set()
            grid, _ = append_bodice_quads(
                bm, bvhs, z_bot=1.135, bottom_ring=None, sleeve_mode="long", neck_style="hood_collar",
                extra_ease=0.0105, pin_verts=pins, trim_faces=trim, hem_trim_h=0.044, cuff_trim=True,
            )
            append_hood_to_collar(bm, bvhs, grid[-1], pins, lining, narrow_shoulders=False)
            _finalize_hoodie_mesh(
                f"lara_street_hoodie_crop_long_{FILE_SUFFIX}", bm, uv, trim, lining, pins, mats,
                has_arms=True, gravity=0.14, z_zip_bot=1.142, z_zip_top=1.466, pocket_z_range=(1.182, 1.268),
                is_skirt=False, armature=armature, rel_out_path=f"streetwear/lara_street_hoodie_crop_long_{FILE_SUFFIX}.glb",
            )

        # 5. Robe hoodie zippée à manches longues
        oid = f"street-dress-hoodie-long-{ID_SUFFIX}"
        if _want(oid):
            bm = bmesh.new()
            uv = bm.loops.layers.uv.new("UVMap")
            pins, trim, lining = set(), set(), set()
            w_ring, z_w = append_skirt_quads(
                bm, bvhs, z_hem=0.675, z_waist=1.060, flare=0.036, pleat_amp=0.0025, pleat_freq=6.0,
                waist_band_h=0.0, pin_verts=pins, trim_faces=trim,
            )
            pins.update(w_ring)
            grid, _ = append_bodice_quads(
                bm, bvhs, z_w, w_ring, "long", "hood_collar",
                extra_ease=0.0090, pin_verts=pins, trim_faces=trim, hem_trim_h=0.0, cuff_trim=True,
            )
            append_hood_to_collar(bm, bvhs, grid[-1], pins, lining, narrow_shoulders=False)
            _finalize_hoodie_mesh(
                f"lara_street_dress_hoodie_long_{FILE_SUFFIX}", bm, uv, trim, lining, pins, mats,
                has_arms=True, gravity=0.25, z_zip_bot=0.700, z_zip_top=1.466, pocket_z_range=(0.915, 1.075),
                is_skirt=True, armature=armature, rel_out_path=f"streetwear/lara_street_dress_hoodie_long_{FILE_SUFFIX}.glb",
            )

        bpy.data.objects.remove(col_full, do_unlink=True)

    if need_sleeveless:
        col_sl, _, _, _ = build_body_collider(include_arms=False, clearance_outer=0.0024)

        # 2. Hoodie zippé sans manches
