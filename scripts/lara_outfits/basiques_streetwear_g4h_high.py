        # 6. Robe hoodie zippée sans manches
        oid = f"street-dress-hoodie-sleeveless-{ID_SUFFIX}"
        if _want(oid):
            bm = bmesh.new()
            uv = bm.loops.layers.uv.new("UVMap")
