def _project_front_surface(bvh: BVHTree, x: float, z: float, offset: float = 0.0022):
    hit, nrm, _, _ = bvh.ray_cast(Vector((x, -0.45, z)), Vector((0.0, 1.0, 0.0)), 0.70)
    if hit is None:
        return None, None
    if nrm.y > 0:
        nrm = -nrm
    return hit + nrm.normalized() * offset, nrm.normalized()


def _add_button(bm: bmesh.types.BMesh, center: Vector, normal: Vector, radius: float = 0.0062, mat_idx: int = 2):
    up = Vector((0.0, 0.0, 1.0)) if abs(normal.z) < 0.9 else Vector((1.0, 0.0, 0.0))
    t1 = normal.cross(up).normalized()
    t2 = normal.cross(t1).normalized()
    n_seg = 10
    ring_b = []
    ring_t = []
    for k in range(n_seg):
        a = (k / n_seg) * 2.0 * math.pi
        radial = (t1 * math.cos(a) + t2 * math.sin(a))
        ring_b.append(bm.verts.new(center + radial * radius - normal * 0.0008))
        ring_t.append(bm.verts.new(center + radial * (radius * 0.85) + normal * 0.0022))
    faces = []
    for k in range(n_seg):
        kn = (k + 1) % n_seg
        faces.append(bm.faces.new((ring_b[k], ring_b[kn], ring_t[kn], ring_t[k])))
    faces.append(bm.faces.new(ring_t))
    for f in faces:
        f.material_index = mat_idx


def _add_pocket_patch(
    bm: bmesh.types.BMesh,
    bvh: BVHTree,
    cx: float,
    cz: float,
    half_w: float,
    half_h: float,
    flap: bool,
    mat_idx: int = 1,
    btn_mat_idx: int = 2,
):
    # Subdivided 3x3 curved grid projected onto garment BVH so patch never dips into curved hips
    grid = []
    for rz in range(3):
        tz = rz / 2.0  # 0=bottom, 1=top
        pz = (cz - half_h) + (2.0 * half_h) * tz
        row = []
        for rx in range(3):
            tx = rx / 2.0
            px = (cx - half_w) + (2.0 * half_w) * tx
            pos, _ = _project_front_surface(bvh, px, pz, offset=0.0028)
            if pos is None:
                return
            row.append(bm.verts.new(pos))
        grid.append(row)
    for rz in range(2):
        for rx in range(2):
            f = bm.faces.new((grid[rz][rx], grid[rz][rx + 1], grid[rz + 1][rx + 1], grid[rz + 1][rx]))
            f.material_index = mat_idx

    if flap:
        f_grid = []
        for rz in range(2):
            pz = cz + half_h * (0.28 if rz == 0 else 1.06)
            row = []
            for rx in range(3):
                tx = rx / 2.0
                px = (cx - half_w * 1.04) + (2.0 * half_w * 1.04) * tx
                z_pt = (pz - half_h * 0.16) if (rz == 0 and rx == 1) else pz
                pos, _ = _project_front_surface(bvh, px, z_pt, offset=0.0038)
                if pos is None:
                    return
                row.append(bm.verts.new(pos))
            f_grid.append(row)
        for rx in range(2):
            ff = bm.faces.new((f_grid[0][rx], f_grid[0][rx + 1], f_grid[1][rx + 1], f_grid[1][rx]))
            ff.material_index = mat_idx
        b_pos, b_nrm = _project_front_surface(bvh, cx, cz + half_h * 0.45, offset=0.0042)
        if b_pos is not None:
            _add_button(bm, b_pos, b_nrm, radius=0.0048, mat_idx=btn_mat_idx)


def _append_flush_details(
    obj: bpy.types.Object,
    button_zs: list[float],
    chest_pockets: bool,
    bib_pocket: bool,
    bib_clasps: bool,
    hip_pockets: bool,
    waist_button_z: float | None,
):
    bm_src = bmesh.new()
    bm_src.from_mesh(obj.data)
    bvh = BVHTree.FromBMesh(bm_src)
    bm_src.free()

    bm = bmesh.new()
    uv_layer = bm.loops.layers.uv.new("UVMap")

    # Placket buttons down center front
    for bz in button_zs:
        pos, nrm = _project_front_surface(bvh, 0.0022, bz, offset=0.0020)
        if pos is not None:
            _add_button(bm, pos, nrm, radius=0.0058, mat_idx=2)

    if waist_button_z is not None:
        pos, nrm = _project_front_surface(bvh, 0.0022, waist_button_z, offset=0.0020)
        if pos is not None:
            _add_button(bm, pos, nrm, radius=0.0066, mat_idx=2)

    if chest_pockets:
        for sx in (-0.056, 0.060):
            _add_pocket_patch(bm, bvh, sx, 1.320, half_w=0.032, half_h=0.036, flap=True, mat_idx=1, btn_mat_idx=2)

