def _add_attached_tucked_edge(
    bm: bmesh.types.BMesh,
    edge_loop_verts: list,
    center: Vector,
    radial_inset: float,
    axial_offset: Vector,
    tuck_faces: set,
):
    """Attach tucked hem return directly to edge_loop_verts (watertight for Cloth, split-shaded post-Cloth)."""
    inner_verts = add_tucked_edge(bm, edge_loop_verts, center, radial_inset, axial_offset)
    for v in inner_verts:
        for f in v.link_faces:
            tuck_faces.add(f)
    return inner_verts


def _leg_hem_for_cut(cut: str, crotch_z: float) -> float:
    return {
        "classic": 0.145,
        "high": 0.145,
        "ripped": 0.145,
        "flare": 0.140,
        "shorts": 0.640,
        "shorty": 0.708,
        "micro_shorty": crotch_z - 0.036,
    }[cut]


def _append_pants_part(
    bm: bmesh.types.BMesh,
    bvhs: dict,
    crotch_z: float,
    cut: str,
    z_waist: float,
    pin_verts: set,
    seam_faces: set,
    uv_layer,
):
    bvh_l = bvhs["bvh_left_leg"]
    verts_l = bvhs["verts_left_leg"]
    bvh_r = bvhs["bvh_right_leg"]
    verts_r = bvhs["verts_right_leg"]
    bvh_p = bvhs["bvh_pelvis"]
    verts_p = bvhs["verts_pelvis"]

    z_hem = _leg_hem_for_cut(cut, crotch_z)
    z_crotch = crotch_z - 0.004

    if cut in ("shorts", "shorty", "micro_shorty"):
        n_rings_leg = 6 if cut == "micro_shorty" else 9
        leg_zs = [z_hem + (z_crotch - z_hem) * (i / (n_rings_leg - 1)) for i in range(n_rings_leg)]
    else:
        # Include explicit dense knee rings around z=0.54 for ripped jeans & crisp knee bend
        raw_zs = [z_hem + (z_crotch - z_hem) * (i / 24.0) for i in range(25)]
        if cut == "ripped":
            knee_zs = [0.490, 0.515, 0.540, 0.565, 0.590]
            raw_zs = [z for z in raw_zs if not (0.482 <= z <= 0.598)] + knee_zs
            raw_zs.sort()
        leg_zs = raw_zs

    leg_rings = {1: [], -1: []}
    leg_data = {
        1: (bvh_l, verts_l, Vector((0.072, 0.0, 0.5))),
        -1: (bvh_r, verts_r, Vector((-0.072, 0.0, 0.5))),
    }

    for side in (1, -1):
        bvh_leg, verts_leg, fb = leg_data[side]
        for zi, z_base in enumerate(leg_zs):
            t_leg = zi / max(1, len(leg_zs) - 1)
            c = slice_centroid_z(verts_leg, z_base, tol=0.028, fallback=fb)
            radii = []
            dirs = []
            for k in range(N_LEG):
                ang = (k / N_LEG) * 2.0 * math.pi
                dx = -side * math.cos(ang)
                dy = math.sin(ang)
                d = Vector((dx, dy, 0.0))
                radii.append(radial_surface_radius(bvh_leg, c, d, max_r=0.14))
                dirs.append(d)

            radii = bridge_convex_radii(radii, max_dip=0.0018, passes=3)
            radii = smooth_ring_radii(radii, passes=2)

            ring_v = []
            for k in range(N_LEG):
                ang = (k / N_LEG) * 2.0 * math.pi
                dx = -side * math.cos(ang)
                outer_amt = max(0.0, side * dx)
                z_pt = z_base
                if zi == 0 and cut in ("shorty", "micro_shorty"):
                    rise = (0.032 if cut == "micro_shorty" else 0.015) * (outer_amt ** 1.2)
                    z_pt = min(z_crotch - 0.006, z_base + rise)
                elif zi == 1 and cut == "micro_shorty":
                    z_pt = min(z_crotch - 0.004, z_base + 0.014 * (outer_amt ** 1.2))

                if cut == "flare":
                    # Fitted thigh & knee, dramatic ankle flare below z=0.50
                    if z_pt < 0.50:
                        tf = (0.50 - z_pt) / max(0.05, 0.50 - z_hem)
                        clr = 0.0075 + 0.034 * (tf ** 1.35)
                    else:
                        clr = 0.0065
                elif cut in ("classic", "high", "ripped"):
                    # Straight-leg denim cylinder ease below thigh
                    if z_pt < 0.54:
                        tf = (0.54 - z_pt) / max(0.05, 0.54 - z_hem)
                        clr = 0.0085 + 0.0115 * tf
                    else:
                        clr = 0.0080
                else:
                    clr = 0.0075 + 0.0020 * outer_amt

                # Prevent inner-thigh crossing near crotch
                if z_pt > 0.62 and (side * dx) < 0.0:
                    inner_t = max(0.0, min(1.0, (z_pt - 0.62) / max(0.05, z_crotch - 0.62))) * abs(dx)
                    clr = max(0.0050, clr * (1.0 - 0.35 * inner_t))

                p = c + dirs[k] * (radii[k] + clr)
                p.z = z_pt
                if side == 1 and p.x < 0.0030:
                    p.x = 0.0030
                elif side == -1 and p.x > 0.0012:
                    p.x = 0.0012
                v = bm.verts.new(p)
                ring_v.append(v)
                if zi == 0 and cut not in ("flare", "classic", "high", "ripped"):
                    # Pin short/shorty leg hems lightly? Actually pin only waist for trousers;
                    # for micro-shorty/shorty pin inner-most hem ring lightly so it keeps exact cut
                    if cut == "micro_shorty":
                        pin_verts.add(v)
            leg_rings[side].append(ring_v)

    leg_face_grid = {1: {}, -1: {}}
    for side in (1, -1):
        rings = leg_rings[side]
        for zi in range(len(rings) - 1):
            r0 = rings[zi]
            r1 = rings[zi + 1]
            for k in range(N_LEG):
                kn = (k + 1) % N_LEG
                if side == -1:
                    f = bm.faces.new((r0[k], r0[kn], r1[kn], r1[k]))
                else:
                    f = bm.faces.new((r0[k], r1[k], r1[kn], r0[kn]))
                leg_face_grid[side][(zi, k)] = f

    # Cut open distressed knee windows for Ripped Jeans
    if cut == "ripped":
        knee_zi = [i for i, z in enumerate(leg_zs) if 0.505 <= z <= 0.570]
        rip_faces = []
        rip_verts = set()
        for side in (1, -1):
            for ri_idx, zi in enumerate(knee_zi[:-1]):
                # Front of leg is around k = 21 (3/4 of N_LEG=28 -> sin(ang) = -1)
                k_span = range(18, 25) if ri_idx == len(knee_zi) // 2 else range(19, 24)
                for k in k_span:
                    f = leg_face_grid[side].get((zi, k))
                    if f and f.is_valid:
                        rip_faces.append(f)
                        rip_verts.update(f.verts)
        if rip_faces:
            bmesh.ops.delete(bm, geom=rip_faces, context="FACES")
            # Subtle organic distress wave along the open rip edge
            for v in rip_verts:
                if v.is_valid and v.is_boundary:
                    v.co.z += 0.0035 * math.sin(v.co.x * 160.0)

    # Tucked ankle / leg hems
    for side in (1, -1):
        _, verts_leg, fb = leg_data[side]
        c_hem = slice_centroid_z(verts_leg, z_hem, tol=0.025, fallback=fb)
        inner_c = _add_attached_tucked_edge(
            bm, leg_rings[side][0], c_hem, 0.0040, Vector((0.0, 0.0, 0.006)), seam_faces
        )
        if any(v in pin_verts for v in leg_rings[side][0]):
            pin_verts.update(inner_c)

    # Anatomical crotch bridge connecting left + right leg top loops -> 56-vert pelvis loop
    l_top = leg_rings[1][-1]
    r_top = leg_rings[-1][-1]
    v_crotch_mid = bm.verts.new(Vector((0.0022, 0.004, z_crotch - 0.004)))
    p_cf = ensure_z_plane_clearance(
        Vector((0.0022, -0.052, z_crotch + 0.024)),
        Vector((0.0022, 0.0)),
        bvh_p,
        0.0060,
        max_r=0.24,
    )
    p_cb = ensure_z_plane_clearance(
        Vector((0.0022, 0.060, z_crotch + 0.024)),
        Vector((0.0022, 0.0)),
        bvh_p,
        0.0060,
        max_r=0.24,
    )
    v_crotch_front = bm.verts.new(p_cf)
    v_crotch_back = bm.verts.new(p_cb)

    bm.faces.new((l_top[0], v_crotch_mid, v_crotch_front, l_top[N_LEG - 1]))
    bm.faces.new((r_top[0], r_top[N_LEG - 1], v_crotch_front, v_crotch_mid))
    bm.faces.new((l_top[0], l_top[1], v_crotch_back, v_crotch_mid))
    bm.faces.new((r_top[0], v_crotch_mid, v_crotch_back, r_top[1]))

    pelvis_loop_0 = (
        [v_crotch_front]
        + [l_top[N_LEG - 1 - i] for i in range(N_LEG - 1)]
        + [v_crotch_back]
        + [r_top[1 + i] for i in range(N_LEG - 1)]
    )
    assert len(pelvis_loop_0) == N_THETA

    n_pelvis_rings = 14
    pelvis_zs = [z_crotch + (z_waist - z_crotch) * (i / n_pelvis_rings) for i in range(1, n_pelvis_rings + 1)]
    pelvis_rings = [pelvis_loop_0]
    for zi, z in enumerate(pelvis_zs):
        c = slice_centroid_z(verts_p, z, tol=0.028, fallback=Vector((0.0022, 0.0, z)))
        radii = []
        dirs = []
        for pi in range(N_THETA):
            theta = -0.5 * math.pi + (pi / N_THETA) * 2.0 * math.pi
            d = Vector((math.cos(theta), math.sin(theta), 0.0))
            radii.append(radial_surface_radius(bvh_p, c, d, max_r=0.25))
            dirs.append(d)

        radii = bridge_convex_radii(radii, max_dip=0.0014, passes=6)
        radii = smooth_ring_radii(radii, passes=2)

        is_band = z >= z_waist - 0.042
        rv = []
        for pi in range(N_THETA):
            clr = 0.0065 if is_band else 0.0072
            p = c + dirs[pi] * (radii[pi] + clr)
            if zi < 2:
                prev_p = pelvis_rings[-1][pi].co
                p = prev_p.lerp(p, 0.45 if zi == 0 else 0.80)
            p = ensure_z_plane_clearance(p, Vector((c.x, c.y)), bvh_p, 0.0052, max_r=0.25)
            v = bm.verts.new(p)
            rv.append(v)
        pelvis_rings.append(rv)

    for zi in range(len(pelvis_rings) - 1):
        r0 = pelvis_rings[zi]
        r1 = pelvis_rings[zi + 1]
        is_band_seg = pelvis_zs[zi] >= z_waist - 0.036
        for pi in range(N_THETA):
            pn = (pi + 1) % N_THETA
            f = bm.faces.new((r0[pi], r0[pn], r1[pn], r1[pi]))
            if is_band_seg:
                seam_faces.add(f)

    top_ring = pelvis_rings[-1]
    return top_ring, z_waist


def _append_skirt_part(
    bm: bmesh.types.BMesh,
    bvhs: dict,
    style: str,
    z_waist: float,
    pin_verts: set,
    seam_faces: set,
):
    bvh_torso = bvhs["bvh_torso"]
    verts_torso = bvhs["verts_torso"]
    bvh_pelvis = bvhs["bvh_pelvis"]
    verts_pelvis = bvhs["verts_pelvis"]
    verts_all_legs = bvhs["verts_pelvis"] + bvhs["verts_left_leg"] + bvhs["verts_right_leg"]

    z_hem = 0.625 if style == "mini" else 0.340
    n_rings = 18 if style == "mini" else 28
    zs = [z_hem + (z_waist - z_hem) * (i / (n_rings - 1)) for i in range(n_rings)]
    a_line_flare = 0.044 if style == "mini" else 0.095

    z_hip_ref = 0.960
    c_hip_ref = slice_centroid_z(verts_pelvis, z_hip_ref, tol=0.028, fallback=Vector((0.0022, -0.006, z_hip_ref)))
    hip_ref_radii = _ray_convex_hull_radii(verts_pelvis, c_hip_ref, z_hip_ref, N_THETA, tol=0.030)
    hip_ref_radii = smooth_ring_radii(hip_ref_radii, passes=2)

    grid = []
    for zi, z in enumerate(zs):
        c = slice_centroid_z(verts_pelvis if z < 1.06 else verts_torso, z, tol=0.028, fallback=Vector((0.0022, -0.006, z)))
        thetas = [-0.5 * math.pi + (j / N_THETA) * 2.0 * math.pi for j in range(N_THETA)]
        dirs = [Vector((math.cos(th), math.sin(th), 0.0)) for th in thetas]

        if z < 0.965:
            t_hang = min(1.0, (0.965 - z) / max(1e-4, 0.965 - z_hem))
            c = c.lerp(Vector((c_hip_ref.x, c_hip_ref.y, z)), 0.78 * t_hang)
            radii_hull = _ray_convex_hull_radii(verts_all_legs, c, z, N_THETA, tol=0.032)
            radii_hull = smooth_ring_radii(radii_hull, passes=2)
            radii = []
            for j in range(N_THETA):
                wave = 0.0030 * math.sin(thetas[j] * 6.0) * (t_hang ** 1.3)
                drape_r = hip_ref_radii[j] * (1.0 - 0.06 * t_hang) + a_line_flare * (t_hang ** 0.92) + wave
                r_req = radii_hull[j] + 0.010 + 0.006 * t_hang
                radii.append(max(r_req, drape_r))
            radii = smooth_ring_radii(radii, passes=2)
        else:
            bvh_src = bvh_torso if z >= 1.06 else bvh_pelvis
            radii = [radial_surface_radius(bvh_src, c, dirs[j], max_r=0.24) for j in range(N_THETA)]
            radii = bridge_convex_radii(radii, max_dip=0.0014, passes=5)
            radii = smooth_ring_radii(radii, passes=2)
            radii = [r + 0.0068 for r in radii]

        rv = []
        for j in range(N_THETA):
            p = Vector((c.x + dirs[j].x * radii[j], c.y + dirs[j].y * radii[j], z))
            if z >= 0.965:
                p = ensure_z_plane_clearance(p, Vector((c.x, c.y)), bvh_pelvis, 0.0052, max_r=0.25)
            rv.append(bm.verts.new(p))
        grid.append(rv)

    for zi in range(len(grid) - 1):
        r0 = grid[zi]
        r1 = grid[zi + 1]
        is_band = zs[zi] >= z_waist - 0.038
        for j in range(N_THETA):
            jn = (j + 1) % N_THETA
            f = bm.faces.new((r0[j], r1[j], r1[jn], r0[jn]))
            if is_band:
                seam_faces.add(f)

    c_hem = slice_centroid_z(verts_all_legs, z_hem, tol=0.032, fallback=Vector((0.0022, -0.006, z_hem)))
    _add_attached_tucked_edge(bm, grid[0], c_hem, 0.0040, Vector((0.0, 0.0, 0.007)), seam_faces)

    return grid[-1], z_waist


