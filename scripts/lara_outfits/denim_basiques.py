def _fit_denim_cloth(obj: bpy.types.Object, pin_indices: set[int], use_gravity: bool):
    if pin_indices:
        vg = obj.vertex_groups.new(name="DenimClothPin")
        vg.add(sorted(pin_indices), 1.0, "REPLACE")

    cloth = obj.modifiers.new("DenimCloth", "CLOTH")
    if pin_indices:
        cloth.settings.vertex_group_mass = "DenimClothPin"
    cloth.settings.quality = 8
    cloth.settings.mass = 0.25
    cloth.settings.tension_stiffness = 38.0
    cloth.settings.compression_stiffness = 38.0
    cloth.settings.shear_stiffness = 22.0
    cloth.settings.bending_stiffness = 2.2
    cloth.settings.air_damping = 1.8
    cloth.settings.effector_weights.gravity = 0.28 if use_gravity else 0.05
    cloth.collision_settings.use_collision = True
    cloth.collision_settings.distance_min = COLLIDER_CLEARANCE
    cloth.collision_settings.use_self_collision = True
    cloth.collision_settings.self_distance_min = 0.0018
    cloth.point_cache.frame_start = 1
    cloth.point_cache.frame_end = CLOTH_FRAMES

    bpy.context.scene.frame_set(1)
    before = [v.co.copy() for v in obj.data.vertices]
    for frame in range(1, CLOTH_FRAMES + 1):
        bpy.context.scene.frame_set(frame)
        ev = obj.evaluated_get(bpy.context.evaluated_depsgraph_get())
        ev.to_mesh()
        ev.to_mesh_clear()

    bpy.context.view_layer.objects.active = obj
    obj.select_set(True)
    bpy.ops.object.modifier_apply(modifier=cloth.name)
    if not all(math.isfinite(c) for v in obj.data.vertices for c in v.co):
        raise RuntimeError(f"{obj.name}: non-finite Cloth output")
    motion = max((v.co - p).length for v, p in zip(obj.data.vertices, before))
    print(f"{obj.name}: Cloth {CLOTH_FRAMES} frames, max motion {motion:.5f} m", flush=True)
    obj.vertex_groups.clear()
    bpy.context.scene.frame_set(1)


