    for f in bm.faces:
        f.smooth = True
        for loop in f.loops:
            co = loop.vert.co
            loop[uv_layer].uv = (co.x * 3.0, co.z * 3.0)

    detail_mesh = bpy.data.meshes.new(f"{obj.name}_details")
    bm.to_mesh(detail_mesh)
    bm.free()
    detail_obj = bpy.data.objects.new(f"{obj.name}_details", detail_mesh)
    bpy.context.scene.collection.objects.link(detail_obj)
    for m in obj.data.materials:
        detail_obj.data.materials.append(m)

    bpy.ops.object.select_all(action="DESELECT")
    obj.select_set(True)
    detail_obj.select_set(True)
    bpy.context.view_layer.objects.active = obj
    bpy.ops.object.join()


