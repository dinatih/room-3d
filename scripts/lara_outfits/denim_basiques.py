def _append_sleeves(
    bm: bmesh.types.BMesh,
    bvhs: dict,
    arm_windows: dict,
    torso_grid: list,
    sleeve_mode: str,
    extra_ease: float,
    pin_verts: set,
    seam_faces: set,
):
    arm_data = {
        1: (bvhs["bvh_left_arm"], bvhs["verts_left_arm"]),
        -1: (bvhs["bvh_right_arm"], bvhs["verts_right_arm"]),
    }

    for side, (z0, z1, j0, j1) in arm_windows.items():
        bvh_arm, verts_arm = arm_data[side]
        hole_verts = []
        for j in range(j0, j1):
            hole_verts.append(torso_grid[z0][j])
        for zi in range(z0, z1):
            hole_verts.append(torso_grid[zi][j1])
        for j in range(j1, j0, -1):
            hole_verts.append(torso_grid[z1][j])
        for zi in range(z1, z0, -1):
            hole_verts.append(torso_grid[zi][j0])

        if sleeve_mode == "none":
            c_hole = sum((v.co for v in hole_verts), Vector()) / len(hole_verts)
            rim = []
            for v in hole_verts:
                in_h = (c_hole - v.co).normalized()
                c_ref = slice_centroid_z(bvhs["verts_torso"], v.co.z, tol=0.03, fallback=Vector((0.0022, -0.01, v.co.z)))
                out_r = Vector((v.co.x - c_ref.x, v.co.y - c_ref.y, 0.0)).normalized()
                iv = bm.verts.new(v.co - out_r * 0.0025 + in_h * 0.0060)
                rim.append(iv)
                pin_verts.add(v)
                pin_verts.add(iv)
            n_sl = len(hole_verts)
            for k in range(n_sl):
                kn = (k + 1) % n_sl
                if side == 1:
                    f = bm.faces.new((hole_verts[k], hole_verts[kn], rim[kn], rim[k]))
                else:
                    f = bm.faces.new((hole_verts[k], rim[k], rim[kn], hole_verts[kn]))
                seam_faces.add(f)
            continue

        n_sl = len(hole_verts)
        x_start = sum(v.co.x for v in hole_verts) / n_sl
        c_sh = slice_centroid_x(verts_arm, x_start, tol=0.03)
        x_end = side * (0.278 if sleeve_mode == "short" else 0.556)
        n_steps = 8 if sleeve_mode == "short" else 16
        hole_angles = [math.atan2(v.co.z - c_sh.z, v.co.y - c_sh.y) for v in hole_verts]

        sleeve_rings = [hole_verts]
        for si in range(1, n_steps + 1):
            t_arm = si / n_steps
            x = x_start + (x_end - x_start) * t_arm
            c_arm = slice_centroid_x(verts_arm, x, tol=0.025)
            is_cuff = (sleeve_mode == "long" and si >= n_steps - 1) or (sleeve_mode == "short" and si == n_steps)
            rv = []
            for k in range(n_sl):
                ang = hole_angles[k]
                d = Vector((0.0, math.cos(ang), math.sin(ang)))
                r = radial_surface_radius(bvh_arm, c_arm, d, max_r=0.11)
                clr = (0.0068 + extra_ease * 0.4) if is_cuff else (0.0085 + extra_ease * 0.75 + 0.0025 * max(0.0, -math.sin(ang)))
                p = c_arm + d * (r + clr)
                if si < 2:
                    p = hole_verts[k].co.lerp(p, 0.60 if si == 0 else 0.85)
                    p.x = x
                    p = ensure_radial_clearance(p, c_arm, bvh_arm, 0.0065, max_r=0.11)
                v = bm.verts.new(p)
                rv.append(v)
                if si == n_steps:
                    pin_verts.add(v)
            sleeve_rings.append(rv)

        for si in range(len(sleeve_rings) - 1):
            r0 = sleeve_rings[si]
            r1 = sleeve_rings[si + 1]
            is_cuff_seg = (sleeve_mode == "long" and si >= n_steps - 2) or (sleeve_mode == "short" and si == n_steps - 1)
            for k in range(n_sl):
                kn = (k + 1) % n_sl
                if side == 1:
                    f = bm.faces.new((r0[k], r0[kn], r1[kn], r1[k]))
                else:
                    f = bm.faces.new((r0[k], r1[k], r1[kn], r0[kn]))
                if is_cuff_seg:
                    seam_faces.add(f)

        end_ring = sleeve_rings[-1]
        c_end = slice_centroid_x(verts_arm, x_end, tol=0.025)
        inner_end = []
        for v in end_ring:
            d_in = Vector((0.0, v.co.y - c_end.y, v.co.z - c_end.z)).normalized()
            iv = bm.verts.new(v.co - d_in * 0.0038 + Vector((-side * 0.006, 0.0, 0.0)))
            inner_end.append(iv)
            pin_verts.add(iv)
        for k in range(n_sl):
            kn = (k + 1) % n_sl
            if side == 1:
                f = bm.faces.new((end_ring[k], end_ring[kn], inner_end[kn], inner_end[k]))
            else:
                f = bm.faces.new((end_ring[k], inner_end[k], inner_end[kn], end_ring[kn]))
            seam_faces.add(f)


def _append_shirt_collar(
    bm: bmesh.types.BMesh,
    bvhs: dict,
    collar_ring: list,
    pin_verts: set,
    seam_faces: set,
):
    """Build a classic folded denim shirt/jacket collar around the top neckline ring."""
    bvh_torso = bvhs["bvh_torso"]
    verts_torso = bvhs["verts_torso"]
    # Skip center-front 2 segments (j=0,1 and n-1) so collar opens in a crisp V-notch at the throat
    indices = list(range(2, N_THETA - 1))
    n_c = len(indices)

    stand_ring = []
    fold_ring = []
    tip_ring = []
    for idx, j in enumerate(indices):
        base = collar_ring[j].co
        t_front = min(idx, n_c - 1 - idx) / max(1.0, (n_c - 1) * 0.5)
        c_ref = slice_centroid_z(verts_torso, base.z + 0.012, tol=0.025, fallback=Vector((0.0022, 0.005, base.z + 0.012)))
        out_dir = Vector((base.x - c_ref.x, base.y - c_ref.y, 0.0))
        if out_dir.length > 1e-5:
            out_dir.normalize()
        else:
            out_dir = Vector((0.0, 1.0, 0.0))

        p_stand = ensure_z_plane_clearance(
            base + out_dir * 0.0025 + Vector((0.0, 0.0, 0.014 * (0.4 + 0.6 * t_front))),
            Vector((c_ref.x, c_ref.y)),
            bvh_torso,
            0.0055,
            max_r=0.14,
        )
        p_fold = p_stand + out_dir * (0.009 + 0.005 * t_front) + Vector((0.0, 0.0, 0.006))
        drop_z = 0.032 - 0.008 * t_front
        out_tip = 0.016 + 0.006 * t_front
        p_tip = p_fold + out_dir * out_tip + Vector((0.0, 0.0, -drop_z))
        p_tip = ensure_z_plane_clearance(p_tip, Vector((c_ref.x, c_ref.y)), bvh_torso, 0.0065, max_r=0.22)

        vs = bm.verts.new(p_stand)
        vf = bm.verts.new(p_fold)
        vt = bm.verts.new(p_tip)
        stand_ring.append(vs)
        fold_ring.append(vf)
        tip_ring.append(vt)
        pin_verts.update((collar_ring[j], vs, vf, vt))

    for k in range(n_c - 1):
        j0, j1 = indices[k], indices[k + 1]
        for f in (
            bm.faces.new((collar_ring[j0], collar_ring[j1], stand_ring[k + 1], stand_ring[k])),
            bm.faces.new((stand_ring[k], stand_ring[k + 1], fold_ring[k + 1], fold_ring[k])),
            bm.faces.new((fold_ring[k], fold_ring[k + 1], tip_ring[k + 1], tip_ring[k])),
        ):
            seam_faces.add(f)


def _append_bodice_part(
    bm: bmesh.types.BMesh,
    bvhs: dict,
    z_bot: float,
    bottom_ring: list | None,
    sleeve_mode: str,
    neck_style: str,
    is_jacket: bool,
    pin_verts: set,
    seam_faces: set,
):
    bvh_torso = bvhs["bvh_torso"]
    verts_torso = bvhs["verts_torso"]
    bvh_pelvis = bvhs["bvh_pelvis"]
    verts_pelvis = bvhs["verts_pelvis"]

    z_collar = 1.468
    n_rings = 24
    zs = [z_bot + (z_collar - z_bot) * (i / (n_rings - 1)) for i in range(n_rings)]
    extra_ease = 0.0080 if is_jacket else 0.0015

    grid = []
    centers = []
    for zi, z in enumerate(zs):
        if zi == 0 and bottom_ring is not None:
            grid.append(bottom_ring)
            centers.append(slice_centroid_z(verts_torso, z, tol=0.028, fallback=Vector((0.0022, -0.010, z))))
            continue

        bvh_src = bvh_torso if z >= 1.08 else bvh_pelvis
        verts_src = verts_torso if z >= 1.08 else verts_pelvis
        c = slice_centroid_z(verts_src, z, tol=0.028, fallback=Vector((0.0022, -0.010, z)))
        centers.append(c)

        thetas = [-0.5 * math.pi + (j / N_THETA) * 2.0 * math.pi for j in range(N_THETA)]
        dirs = [Vector((math.cos(th), math.sin(th), 0.0)) for th in thetas]
        radii = [radial_surface_radius(bvh_src, c, dirs[j], max_r=0.22) for j in range(N_THETA)]
        radii = bridge_convex_radii(radii, max_dip=0.0014, passes=6)
        radii = smooth_ring_radii(radii, passes=2)

        rv = []
        for j in range(N_THETA):
            th = thetas[j]
            r_eff = radii[j]
            if sleeve_mode == "none" and z >= 1.425:
                t_up = min(1.0, max(0.0, (z - 1.425) / max(1e-5, z_collar - 1.425)))
                max_lat = (0.104 if neck_style == "tank_scoop" else 0.112) - 0.044 * (t_up ** 0.75)
                lat_w = abs(math.cos(th))
                if lat_w > 0.25 and r_eff * lat_w > max_lat:
                    r_eff = max_lat / lat_w

            z_mod = z
            if neck_style == "tank_scoop" and zi >= n_rings - 7:
                t_top = (zi - (n_rings - 7)) / 6.0
                front_scoop = 0.120 * max(0.0, -math.sin(th)) ** 1.45
                back_scoop = 0.085 * max(0.0, math.sin(th)) ** 1.40
                z_mod = z - t_top * (front_scoop + back_scoop)
            elif neck_style == "shirt_collar" and zi >= n_rings - 4:
                t_top = (zi - (n_rings - 4)) / 3.0
                front_v = 0.036 * max(0.0, -math.sin(th)) ** 4.0
                z_mod = z - t_top * front_v

            c_m = slice_centroid_z(verts_torso if z_mod >= 1.08 else verts_pelvis, z_mod, tol=0.028, fallback=Vector((c.x, c.y, z_mod)))
            if z_mod < 1.425 and zi >= n_rings - 7:
                r_m = radial_surface_radius(bvh_torso, c_m, dirs[j], max_r=0.22)
                r_eff = 0.62 * r_m + 0.38 * r_eff

            if is_jacket:
                clr = 0.0135 if z_mod < 1.24 else (0.0110 if z_mod < 1.40 else 0.0095)
            else:
                clr = 0.0068 if z_mod < 1.24 else (0.0058 if z_mod < 1.40 else 0.0052)

            p = c_m + dirs[j] * (r_eff + clr)
            if z_mod < 1.425:
                min_clr = 0.0090 if is_jacket else 0.0046
                p = ensure_z_plane_clearance(p, Vector((c_m.x, c_m.y)), bvh_torso if z_mod >= 1.08 else bvh_pelvis, min_clr, max_r=0.22)
            v = bm.verts.new(p)
            rv.append(v)
            # Pin shoulder apex & collar edge so top stays anchored during Cloth
            if zi == n_rings - 1 or (z >= 1.445 and abs(math.cos(th)) > 0.65):
                pin_verts.add(v)
        grid.append(rv)

    is_tank_arm = sleeve_mode == "none"
    z_arm_bot_target = 1.300 if is_tank_arm else 1.335
    z_arm_top_target = 1.460 if is_tank_arm else 1.462
    zi_arm_bot = min(range(n_rings), key=lambda i: abs(zs[i] - z_arm_bot_target))
    zi_arm_top = min(n_rings - 2, max(zi_arm_bot + 5, min(range(n_rings), key=lambda i: abs(zs[i] - z_arm_top_target))))
    j_l_mid = N_THETA // 4
    j_r_mid = (3 * N_THETA) // 4
    half_w = 4 if is_tank_arm else 3
    arm_windows = {
        1: (zi_arm_bot, zi_arm_top, j_l_mid - half_w, j_l_mid + half_w),
        -1: (zi_arm_bot, zi_arm_top, j_r_mid - half_w, j_r_mid + half_w),
    }

    def _in_armhole(zi, j):
        for z0, z1, j0, j1 in arm_windows.values():
            if z0 <= zi < z1 and j0 <= j < j1:
                return True
        return False

    for zi in range(n_rings - 1):
        is_jacket_band = is_jacket and zi <= 1
        for j in range(N_THETA):
            if _in_armhole(zi, j):
                continue
            jn = (j + 1) % N_THETA
            f = bm.faces.new((grid[zi][j], grid[zi][jn], grid[zi + 1][jn], grid[zi + 1][j]))
            if is_jacket_band:
                seam_faces.add(f)

    if bottom_ring is None:
        _add_attached_tucked_edge(bm, grid[0], centers[0], 0.0040, Vector((0.0, 0.0, 0.006)), seam_faces)

    if neck_style == "shirt_collar":
        _append_shirt_collar(bm, bvhs, grid[-1], pin_verts, seam_faces)
    else:
        inner_neck = _add_attached_tucked_edge(bm, grid[-1], centers[-1], 0.0032, Vector((0.0, 0.0, -0.005)), seam_faces)
        pin_verts.update(inner_neck)

    _append_sleeves(bm, bvhs, arm_windows, grid, sleeve_mode, extra_ease, pin_verts, seam_faces)
    return grid


def _append_overalls_bib_and_straps(
    bm: bmesh.types.BMesh,
    bvhs: dict,
    waist_ring: list,
    z_waist: float,
    pin_verts: set,
    seam_faces: set,
):
    """Build front bib, back bib, and two shoulder straps directly onto the 56-vert waist ring."""
    bvh_torso = bvhs["bvh_torso"]
    verts_torso = bvhs["verts_torso"]

    # Front bib: indices wrapping j=0 (-pi/2 front): [-10..+10] -> 21 vertices across full chest
    front_indices = [(N_THETA - 10 + k) % N_THETA for k in range(21)]
    n_fb_rows = 10
    z_fb_top = 1.350
    fb_grid = [[waist_ring[j] for j in front_indices]]
    for ri in range(1, n_fb_rows + 1):
        t = ri / n_fb_rows
        z = z_waist + (z_fb_top - z_waist) * t
        c = slice_centroid_z(verts_torso, z, tol=0.028, fallback=Vector((0.0022, -0.010, z)))
        row_pts = []
        for ki, j in enumerate(front_indices):
            u = (ki / (len(front_indices) - 1)) * 2.0 - 1.0  # -1 (right) .. +1 (left)
            half_ang = (0.72 - 0.14 * (t ** 0.85)) * math.pi * 0.5
            th = -0.5 * math.pi + u * half_ang
            d = Vector((math.cos(th), math.sin(th), 0.0))
            r = radial_surface_radius(bvh_torso, c, d, max_r=0.22)
            row_pts.append((d, r))
        rs = bridge_convex_radii([r for _, r in row_pts], max_dip=0.0010, passes=5)
        row = []
        for ki, (d, _) in enumerate(row_pts):
            p = ensure_z_plane_clearance(c + d * (rs[ki] + 0.0085), Vector((c.x, c.y)), bvh_torso, 0.0070, max_r=0.22)
            v = bm.verts.new(p)
            row.append(v)
            if ri == n_fb_rows:
                pin_verts.add(v)
        fb_grid.append(row)

    for ri in range(len(fb_grid) - 1):
        for ki in range(len(front_indices) - 1):
            f = bm.faces.new((fb_grid[ri][ki], fb_grid[ri][ki + 1], fb_grid[ri + 1][ki + 1], fb_grid[ri + 1][ki]))
            if ri == len(fb_grid) - 2:
                seam_faces.add(f)

    # Back bib: indices around j=28 (+pi/2 back): [20..36] -> 17 vertices
    back_indices = list(range(20, 37))
    n_bb_rows = 6
    z_bb_top = 1.245
    bb_grid = [[waist_ring[j] for j in back_indices]]
    for ri in range(1, n_bb_rows + 1):
        t = ri / n_bb_rows
        z = z_waist + (z_bb_top - z_waist) * t
        c = slice_centroid_z(verts_torso, z, tol=0.028, fallback=Vector((0.0022, -0.010, z)))
        row = []
        for ki in range(len(back_indices)):
            u = (ki / (len(back_indices) - 1)) * 2.0 - 1.0  # -1 (left) .. +1 (right)
            half_ang = (0.52 - 0.14 * t) * math.pi * 0.5
            th = 0.5 * math.pi + u * half_ang
            d = Vector((math.cos(th), math.sin(th), 0.0))
            r = radial_surface_radius(bvh_torso, c, d, max_r=0.22)
            p = ensure_z_plane_clearance(c + d * (r + 0.0080), Vector((c.x, c.y)), bvh_torso, 0.0065, max_r=0.22)
            v = bm.verts.new(p)
            row.append(v)
            if ri == n_bb_rows:
                pin_verts.add(v)
        bb_grid.append(row)

    for ri in range(len(bb_grid) - 1):
        for ki in range(len(back_indices) - 1):
            f = bm.faces.new((bb_grid[ri][ki], bb_grid[ri][ki + 1], bb_grid[ri + 1][ki + 1], bb_grid[ri + 1][ki]))
            if ri == len(bb_grid) - 2:
                seam_faces.add(f)

    # Tuck exposed side waist gaps between front bib & back bib
    for gap_indices in (list(range(10, 21)), list(range(36, 47))):
        gap_verts = [waist_ring[j] for j in gap_indices]
        c_w = slice_centroid_z(verts_torso, z_waist, tol=0.028, fallback=Vector((0.0022, -0.010, z_waist)))
        inner = []
        for v in gap_verts:
            d = Vector((v.co.x - c_w.x, v.co.y - c_w.y, 0.0)).normalized()
            iv = bm.verts.new(v.co - d * 0.0035 + Vector((0.0, 0.0, -0.006)))
            inner.append(iv)
            pin_verts.add(v)
            pin_verts.add(iv)
        for k in range(len(gap_verts) - 1):
            f = bm.faces.new((gap_verts[k], gap_verts[k + 1], inner[k + 1], inner[k]))
            seam_faces.add(f)

    # Two shoulder straps (4 verts wide) arched cleanly above shoulders/clavicles/scapulae
    strap_pairs = [
        (fb_grid[-1][-4:], list(reversed(bb_grid[-1][:4])), 1),
        (fb_grid[-1][:4], list(reversed(bb_grid[-1][-4:])), -1),
    ]
    n_strap_steps = 16
    for f_vs, b_vs, side in strap_pairs:
        strap_rows = [f_vs]
        for si in range(1, n_strap_steps):
            t = si / n_strap_steps
            row = []
            for wi in range(4):
                p_lin = f_vs[wi].co.lerp(b_vs[wi].co, t)
                arch = math.sin(t * math.pi)
                p_lin.z = max(p_lin.z, 1.350 + 0.125 * (arch ** 0.72))
                # Raycast directly against torso from front / top / back so straps never enter scapulae
                if t <= 0.42:
                    hit_f, _, _, _ = bvh_torso.ray_cast(Vector((p_lin.x, -0.35, p_lin.z)), Vector((0.0, 1.0, 0.0)), 0.60)
                    if hit_f is not None:
                        p_lin.y = min(p_lin.y, hit_f.y - 0.010)
                elif t >= 0.58:
                    hit_b, _, _, _ = bvh_torso.ray_cast(Vector((p_lin.x, 0.35, p_lin.z)), Vector((0.0, -1.0, 0.0)), 0.60)
                    if hit_b is not None:
                        p_lin.y = max(p_lin.y, hit_b.y + 0.010)
                hit_top, _, _, _ = bvh_torso.ray_cast(Vector((p_lin.x, p_lin.y, 1.65)), Vector((0.0, 0.0, -1.0)), 0.40)
                if hit_top is not None and hit_top.z > 1.38:
                    p_lin.z = max(p_lin.z, hit_top.z + 0.010)
                p_lin = ensure_3d_surface_clearance(p_lin, bvh_torso, 0.0105, max_dist=0.07)
                v = bm.verts.new(p_lin)
                row.append(v)
                pin_verts.add(v)
            strap_rows.append(row)
        strap_rows.append(b_vs)
        for si in range(len(strap_rows) - 1):
            for wi in range(3):
                f = bm.faces.new((strap_rows[si][wi], strap_rows[si][wi + 1], strap_rows[si + 1][wi + 1], strap_rows[si + 1][wi]))
                seam_faces.add(f)


