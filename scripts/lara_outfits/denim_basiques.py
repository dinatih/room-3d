def _build_denim_collider():
    bm = bmesh.new()
    for name in ("body_nude_torso", "body_nude_legs", "body_nude_feet", "arms"):
        src = bpy.data.objects.get(name)
        if not src:
            raise RuntimeError(f"Missing Lara reference mesh: {name}")
        bm_part = bmesh.new()
        bm_part.from_mesh(src.data)
        if name == "arms":
            # Trim arm ends inside torso shoulder cavity so they don't create internal spikes.
            inside = [v for v in bm_part.verts if abs(v.co.x) < 0.132]
            if inside:
                bmesh.ops.delete(bm_part, geom=inside, context="VERTS")
        _orient_mesh_islands_outward(bm_part)
        tmp = bpy.data.meshes.new(f"_tmp_col_{name}")
        bm_part.to_mesh(tmp)
        bm_part.free()
        bm.from_mesh(tmp)
        bpy.data.meshes.remove(tmp)

    bmesh.ops.remove_doubles(bm, verts=list(bm.verts), dist=1e-5)
    bm.normal_update()
    bvh = BVHTree.FromBMesh(bm)
    hit, _, _, _ = bvh.ray_cast(Vector((0.0, 0.0, 0.40)), Vector((0.0, 0.0, 1.0)), 1.0)
    if hit is None:
        raise RuntimeError("Cannot measure Lara crotch height")
    crotch_z = hit.z

    mesh = bpy.data.meshes.new("Denim_Body_Collider_Mesh")
    bm.to_mesh(mesh)
    bm.free()
    collider = bpy.data.objects.new("Denim_Body_Collider", mesh)
    bpy.context.scene.collection.objects.link(collider)
    collider.modifiers.new("DenimBodyCollision", "COLLISION")
    collider.collision.thickness_outer = COLLIDER_CLEARANCE
    collider.collision.thickness_inner = 0.005
    collider.collision.damping = 0.25
    return collider, crotch_z


