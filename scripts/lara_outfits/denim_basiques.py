def _build_single_denim_garment(spec: dict, bvhs: dict, mats: dict, armature, crotch_z: float):
    bm = bmesh.new()
    uv_layer = bm.loops.layers.uv.new("UVMap")
    pin_verts = set()
    seam_faces = set()

    kind = spec["kind"]
    use_gravity = False

    if kind == "top":
        _append_bodice_part(
            bm, bvhs, spec["z_bot"], None, spec["sleeves"], spec["neck"], spec["is_jacket"], pin_verts, seam_faces
        )
    elif kind == "bottom_pants":
        waist_ring, z_w = _append_pants_part(bm, bvhs, crotch_z, spec["cut"], spec["z_waist"], pin_verts, seam_faces, uv_layer)
        c_w = slice_centroid_z(bvhs["verts_pelvis"], z_w, tol=0.028, fallback=Vector((0.0022, 0.0, z_w)))
        inner_w = _add_attached_tucked_edge(bm, waist_ring, c_w, 0.0040, Vector((0.0, 0.0, -0.006)), seam_faces)
        pin_verts.update(waist_ring)
        pin_verts.update(inner_w)
    elif kind == "bottom_skirt":
        use_gravity = True
        waist_ring, z_w = _append_skirt_part(bm, bvhs, spec["style"], spec["z_waist"], pin_verts, seam_faces)
        c_w = slice_centroid_z(bvhs["verts_pelvis"], z_w, tol=0.028, fallback=Vector((0.0022, 0.0, z_w)))
        inner_w = _add_attached_tucked_edge(bm, waist_ring, c_w, 0.0040, Vector((0.0, 0.0, -0.006)), seam_faces)
        pin_verts.update(waist_ring)
        pin_verts.update(inner_w)
    elif kind == "jumpsuit_pants":
        waist_ring, z_w = _append_pants_part(bm, bvhs, crotch_z, spec["cut"], spec["z_waist"], pin_verts, seam_faces, uv_layer)
        pin_verts.update(waist_ring)
        _append_bodice_part(bm, bvhs, z_w, waist_ring, spec["sleeves"], spec["neck"], False, pin_verts, seam_faces)
    elif kind == "jumpsuit_skirt":
        use_gravity = True
        waist_ring, z_w = _append_skirt_part(bm, bvhs, spec["style"], spec["z_waist"], pin_verts, seam_faces)
        pin_verts.update(waist_ring)
        _append_bodice_part(bm, bvhs, z_w, waist_ring, spec["sleeves"], spec["neck"], False, pin_verts, seam_faces)
    elif kind == "overalls_pants":
        waist_ring, z_w = _append_pants_part(bm, bvhs, crotch_z, spec["cut"], spec["z_waist"], pin_verts, seam_faces, uv_layer)
        _append_overalls_bib_and_straps(bm, bvhs, waist_ring, z_w, pin_verts, seam_faces)
    elif kind == "overalls_skirt":
        use_gravity = True
        waist_ring, z_w = _append_skirt_part(bm, bvhs, spec["style"], spec["z_waist"], pin_verts, seam_faces)
        _append_overalls_bib_and_straps(bm, bvhs, waist_ring, z_w, pin_verts, seam_faces)
    else:
        raise RuntimeError(f"Unknown denim garment kind: {kind}")

    _orient_mesh_islands_outward(bm)
    for f in bm.faces:
        f.smooth = True
        f.material_index = 1 if f in seam_faces else 0
        for loop in f.loops:
            co = loop.vert.co
            if abs(co.x) > 0.165 and co.z > 1.30:
                ang = math.atan2(co.z - 1.42, co.y)
                loop[uv_layer].uv = ((ang / (2.0 * math.pi) + 0.5) * 1.4, abs(co.x) * 2.2)
            else:
                cx = 0.068 if (co.z < 0.78 and co.x > 0.015) else (-0.068 if (co.z < 0.78 and co.x < -0.015) else 0.0)
                ang = math.atan2(co.y, co.x - cx)
                loop[uv_layer].uv = ((ang / (2.0 * math.pi) + 0.5) * 1.8, co.z * 2.2)

    bm.verts.index_update()
    pin_indices = {v.index for v in pin_verts if v.is_valid}

    obj_name = "lara_" + spec["id"].replace("-", "_")
    mesh = bpy.data.meshes.new(obj_name)
    bm.to_mesh(mesh)
    bm.free()

    obj = bpy.data.objects.new(obj_name, mesh)
    bpy.context.scene.collection.objects.link(obj)
    obj.data.materials.append(mats["denim"])
    obj.data.materials.append(mats["denim_seam"])
    obj.data.materials.append(mats["denim_hardware"])

    _fit_denim_cloth(obj, pin_indices, use_gravity=use_gravity)

    # Split sharp seam/hem boundary edges post-Cloth so inward hem tucks don't darken outer normals
    bm_post = bmesh.new()
    bm_post.from_mesh(obj.data)
    split_edges = [
        e for e in bm_post.edges
        if len(e.link_faces) == 2 and e.link_faces[0].material_index != e.link_faces[1].material_index
    ]
    if split_edges:
        bmesh.ops.split_edges(bm_post, edges=split_edges)
        bm_post.to_mesh(obj.data)
    bm_post.free()
    for p in obj.data.polygons:
        p.use_smooth = True

    waist_btn_z = (spec["z_waist"] - 0.018) if kind == "bottom_pants" else None
    _append_flush_details(
        obj,
        button_zs=spec.get("buttons", []),
        chest_pockets=spec.get("chest_pockets", False),
        bib_pocket=spec.get("bib_pocket", False),
        bib_clasps=spec.get("bib_clasps", False),
        hip_pockets=spec.get("hip_pockets", False),
        waist_button_z=waist_btn_z,
    )

    donor_torso = [bpy.data.objects["body_nude_torso"], bpy.data.objects["body_nude_panties"]]
    donor_legs = [bpy.data.objects["body_nude_feet"], bpy.data.objects["body_nude_legs"], bpy.data.objects["body_nude_panties"]]
    donor_arms = [bpy.data.objects["arms"]]

    def _select_donors(vco):
        if abs(vco.x) > 0.145 and vco.z > 1.320:
            return donor_arms
        if vco.z < 0.960:
            return donor_legs
        return donor_torso

    all_donors = donor_torso + donor_legs + donor_arms
    bind_and_transfer_weights(
        obj,
        all_donors,
        armature,
        bone_attenuation={"breast_left_base": 0.55, "breast_right_base": 0.55},
        smooth_passes=3 if "skirt" in kind else 1,
        region_selector=_select_donors,
    )
    obj["generation"] = GENERATION_TAG
    obj["cloth_fit_frames"] = CLOTH_FRAMES
    export_garment_glb([obj], armature, spec["path"])
    obj.hide_render = True
    return obj


def generate_denim_basiques(bvhs, mats, armature, only_ids: set[str] | None = None):
    collider, crotch_z = _build_denim_collider()
    print(f"Basiques Denim ({GENERATION_TAG}): crotch={crotch_z:.5f} m", flush=True)
    for spec in DENIM_SPECS:
        if only_ids is not None and spec["id"] not in only_ids:
            continue
        obj = _build_single_denim_garment(spec, bvhs, mats, armature, crotch_z)
        bpy.data.objects.remove(obj, do_unlink=True)
    bpy.data.objects.remove(collider, do_unlink=True)
