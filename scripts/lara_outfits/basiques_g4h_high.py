"""CLI entry point to generate Lara's Basiques 01/02/03 collections with Blender Cloth.

Generated by Gemini 4 Hydrogen (effort: High).

Usage:
  blender --background --threads 4 --python-exit-code 1 --python scripts/lara_outfits/basiques_g4h_high.py
  blender --background --threads 4 --python-exit-code 1 --python scripts/lara_outfits/basiques_g4h_high.py -- --chart 01
  blender --background --threads 4 --python-exit-code 1 --python scripts/lara_outfits/basiques_g4h_high.py -- --only swim-trikini-g4h-high
"""

import argparse
import os
import sys
import bpy

REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
if REPO_ROOT not in sys.path:
    sys.path.insert(0, REPO_ROOT)

from scripts.lara_outfits.basiques_sport_g4h_high import generate_basiques_sport
from scripts.lara_outfits.basiques_streetwear_g4h_high import generate_basiques_streetwear
from scripts.lara_outfits.basiques_swimwear_g4h_high import generate_basiques_swimwear
from scripts.lara_outfits.common import BLEND_PATH
from scripts.lara_outfits.geometry import build_body_bvhs
from scripts.lara_outfits.materials import create_material_library


CHARTS = {
    "01": generate_basiques_swimwear,
    "02": generate_basiques_sport,
    "03": generate_basiques_streetwear,
}


def generate_basiques_g4h_high(bvhs, mats, armature, only_ids=None):
    for chart_fn in CHARTS.values():
        chart_fn(bvhs, mats, armature, only_ids=only_ids)


def _parse_args():
    argv = sys.argv[sys.argv.index("--") + 1 :] if "--" in sys.argv else []
    parser = argparse.ArgumentParser(description="Build Lara Basiques 01/02/03 outfits (Gemini 4 Hydrogen, High)")
    parser.add_argument("--chart", nargs="*", choices=sorted(CHARTS.keys()), help="Chart(s) to generate: 01, 02, 03")
    parser.add_argument("--only", nargs="*", help="Specific outfit IDs to generate")
    return parser.parse_args(argv)


def main():
    args = _parse_args()
    bpy.ops.wm.open_mainfile(filepath=BLEND_PATH)
    armature = bpy.data.objects["Armature"]
    mats = create_material_library()
    bvhs = build_body_bvhs()

    selected = args.chart if args.chart else list(CHARTS.keys())
    only_ids = set(args.only) if args.only else None
    for ch in selected:
        CHARTS[ch](bvhs, mats, armature, only_ids=only_ids)

    print("Basiques 01/02/03 (Gemini 4 Hydrogen High) generation complete!", flush=True)


if __name__ == "__main__":
    main()
