def _smooth01(x: float) -> float:
    x = max(0.0, min(1.0, x))
    return x * x * (3.0 - 2.0 * x)


def _brief_cut_sdf(crotch_z: float, band_bottom: float, front_w: float, back_w: float, gusset_w: float = 0.024):
    """Smooth continuous SDF for lower-body brief leg cutouts (no hard y=0 step)."""
    crotch_ref = crotch_z - 0.016

    def sdf(p: Vector) -> float:
        if p.z >= band_bottom:
            return 1.0
        t = (p.z - crotch_ref) / max(1e-4, band_bottom - crotch_ref)
        t_back = _smooth01((p.y + 0.025) / 0.050)
        panel_w = front_w * (1.0 - t_back) + back_w * t_back
        w = gusset_w + (panel_w - gusset_w) * math.copysign(abs(t) ** 1.12, t)
        return w - abs(p.x)

    return sdf


def _armhole_and_shoulder_sdf(z_arm_bot: float = 1.292, x_arm_bot: float = 0.122, x_shoulder_out: float = 0.106):
    """Keep torso inside deltoid/armholes above z_arm_bot."""
    def sdf(p: Vector) -> float:
        if p.z <= z_arm_bot:
            return 1.0
        t = _smooth01((p.z - z_arm_bot) / (1.468 - z_arm_bot))
        x_lim = x_arm_bot * (1.0 - t) + x_shoulder_out * t
        return x_lim - abs(p.x)
    return sdf


def _build_fullcover_swimsuit(bvhs, mats, armature, crotch_z: float):
    """12. Maillot couvrant: full-coverage long-sleeve ankle-length mock-neck swimsuit."""
    bm = bmesh.new()
    uv_layer = bm.loops.layers.uv.new("UVMap")
    pin_verts = set()
    trim_faces = set()

    waist_ring, z_w = append_pants_quads(
        bm, bvhs, crotch_z, z_hem=0.148, z_waist=1.060,
        leg_ease_fn=lambda z, ang, side, zi, n: (0.0046, z),
        pelvis_ease_fn=lambda z, th: 0.0048,
        pin_verts=pin_verts, trim_faces=trim_faces,
        cuff_z_band=0.0, waist_z_band=0.0, pin_hem=True,
    )
    pin_verts.update(waist_ring)
    append_bodice_quads(
        bm, bvhs, z_w, waist_ring, "long", "mock_neck",
        extra_ease=0.0, pin_verts=pin_verts, trim_faces=trim_faces,
        hem_trim_h=0.0, cuff_trim=False,
    )
    _orient_mesh_islands_outward(bm)
    for f in bm.faces:
        f.smooth = True
        f.material_index = 0
        for loop in f.loops:
            co = loop.vert.co
            if abs(co.x) > 0.165 and co.z > 1.30:
                ang = math.atan2(co.z - 1.42, co.y)
                loop[uv_layer].uv = ((ang / (2.0 * math.pi) + 0.5) * 1.4, abs(co.x) * 2.2)
            else:
                cx = 0.068 if (co.z < 0.78 and co.x > 0.015) else (-0.068 if (co.z < 0.78 and co.x < -0.015) else 0.0)
                ang = math.atan2(co.y, co.x - cx)
                loop[uv_layer].uv = ((ang / (2.0 * math.pi) + 0.5) * 1.8, co.z * 2.2)

    bm.verts.index_update()
    pin_idx = {v.index for v in pin_verts if v.is_valid}
    mesh = bpy.data.meshes.new(f"lara_swim_fullcover_{FILE_SUFFIX}")
    bm.to_mesh(mesh)
    bm.free()
    obj = bpy.data.objects.new(mesh.name, mesh)
    bpy.context.scene.collection.objects.link(obj)
    obj.data.materials.append(mats["swimwear"])

    fit_cloth_sim(obj, pin_idx, frames=14, mass=0.15, tension=38.0, compression=38.0, shear=18.0, bending=0.8, gravity=0.0)
    finalize_and_export(obj, armature, f"swimwear/lara_swim_fullcover_{FILE_SUFFIX}.glb", has_arms=True, breast_atten=0.65, cloth_frames=14)
    bpy.data.objects.remove(obj, do_unlink=True)


