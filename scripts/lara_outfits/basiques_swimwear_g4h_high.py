            # Pelvis brief covers body_nude_panties cleanly up to z = 1.032
            if p.z <= 1.032:
                return 1.0
            t_back = _smooth01((p.y + 0.010) / 0.045)
            # Waist cutout zone: 1.032 < z < 1.235 -> narrow center front hourglass strip + thin back strap at 1.222..1.250
            if p.z < 1.235:
                tz = (p.z - 1.133) / 0.101  # -1..+1
                front_strip_w = 0.044 + 0.088 * (tz * tz)
                front_ok = front_strip_w - abs(p.x) if p.y < 0.010 else -1.0
                back_band_ok = min(p.z - 1.220, 1.252 - p.z) if p.y >= -0.010 else -1.0
