def join_objects(target: bpy.types.Object, parts: list[bpy.types.Object]):
    """Join secondary detail objects into target while preserving material slots."""
    valid = [p for p in parts if p is not None and len(p.data.polygons) > 0]
    if not valid:
        return
    bpy.ops.object.select_all(action="DESELECT")
    target.select_set(True)
    for p in valid:
        p.select_set(True)
    bpy.context.view_layer.objects.active = target
    bpy.ops.object.join()


