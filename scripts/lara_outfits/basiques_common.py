def build_body_collider(*, include_arms: bool = True, clearance_outer: float = 0.0024):
    """Build a watertight outward-oriented collision mesh from Lara's native skin."""
    bm = bmesh.new()
    names = ["body_nude_legs", "body_nude_feet", "body_nude_torso"]
    if include_arms:
        names.append("arms")

    for name in names:
        src = bpy.data.objects.get(name)
        if not src:
            raise RuntimeError(f"Missing Lara reference mesh: {name}")
        bm_part = bmesh.new()
        bm_part.from_mesh(src.data)
        if name == "arms":
            inside = [v for v in bm_part.verts if abs(v.co.x) < 0.132]
            if inside:
                bmesh.ops.delete(bm_part, geom=inside, context="VERTS")
        _orient_mesh_islands_outward(bm_part)
        tmp = bpy.data.meshes.new(f"_tmp_col_{name}")
        bm_part.to_mesh(tmp)
        bm_part.free()
        bm.from_mesh(tmp)
        bpy.data.meshes.remove(tmp)

    bmesh.ops.remove_doubles(bm, verts=list(bm.verts), dist=1e-5)
    boundary_edges = [e for e in bm.edges if e.is_boundary]
    if boundary_edges:
        bmesh.ops.holes_fill(bm, edges=boundary_edges)
    _orient_mesh_islands_outward(bm)
    bm.normal_update()

    bvh = BVHTree.FromBMesh(bm)
    hit, _, _, _ = bvh.ray_cast(Vector((0.0, 0.0, 0.30)), Vector((0.0, 0.0, 1.0)), 1.0)
    if hit is None:
        raise RuntimeError("Cannot measure Lara anatomical crotch height")
    crotch_z = hit.z

    mesh = bpy.data.meshes.new(f"Basiques_Collider_{'Full' if include_arms else 'Torso'}")
    bm.to_mesh(mesh)
    bm.free()
    collider = bpy.data.objects.new(mesh.name, mesh)
    bpy.context.scene.collection.objects.link(collider)
    collider.modifiers.new("BodyCollision", "COLLISION")
    collider.collision.thickness_outer = clearance_outer
    collider.collision.thickness_inner = 0.005
    collider.collision.damping = 0.25

    bikini_obj = bpy.data.objects["bikini_bottom"]
    bikini_waist_z = max((bikini_obj.matrix_world @ v.co).z for v in bikini_obj.data.vertices)
    return collider, bvh, crotch_z, bikini_waist_z


def _clip_polygon(points: list[Vector], distance_fn) -> list[Vector]:
    result = []
    n = len(points)
    for i in range(n):
        a = points[i]
        b = points[(i + 1) % n]
        da = distance_fn(a)
        db = distance_fn(b)
        if da >= 0.0:
            result.append(a)
        if (da < 0.0) != (db < 0.0):
            t = da / (da - db)
            result.append(a.lerp(b, t))
    return result


def _bridge_cleavage_bmesh(bm: bmesh.types.BMesh, z_min: float = 1.215, z_max: float = 1.385, x_span: float = 0.068):
    """Smoothly bridge the front sternum valley between the breasts so fabric stretches naturally."""
    front_verts = [
        v for v in bm.verts
        if v.co.y < -0.04 and z_min <= v.co.z <= z_max and abs(v.co.x) <= x_span + 0.015
    ]
    if not front_verts:
        return
    # Compute reference envelope from outer breast peaks at similar Z
    peaks = [v.co.copy() for v in bm.verts if v.co.y < -0.06 and 1.24 <= v.co.z <= 1.36 and 0.045 <= abs(v.co.x) <= 0.095]
    if not peaks:
        return
    for v in front_verts:
        t_z = 1.0 - abs(v.co.z - 1.300) / max(0.05, 0.5 * (z_max - z_min))
        t_z = max(0.0, min(1.0, t_z))
        t_x = max(0.0, 1.0 - (abs(v.co.x) / x_span) ** 1.6)
        if t_x <= 0.0 or t_z <= 0.0:
            continue
        # Target front envelope interpolates slightly recessed relative to peaks (natural draped bridge)
        target_y = -0.146 + 0.020 * (1.0 - t_z) + 0.008 * t_x
        if v.co.y > target_y:
            blend = 0.72 * t_x * (0.4 + 0.6 * t_z)
            v.co.y = v.co.y * (1.0 - blend) + target_y * blend


def cut_body_surface(
    name: str,
    collider_obj: bpy.types.Object,
    distances: list,
    materials: list,
    *,
    subdivide_cuts: int = 1,
    clearance: float = 0.0042,
    bridge_bust: bool = False,
    pin_boundary: bool = True,
    pin_predicate=None,
    mat_index_fn=None,
    uv_scale: tuple[float, float] = (1.8, 2.2),
):
    """Clip a refined copy of the outward body surface using signed-distance functions."""
    bm = bmesh.new()
    bm.from_mesh(collider_obj.data)
    if subdivide_cuts > 0:
        bmesh.ops.subdivide_edges(bm, edges=list(bm.edges), cuts=subdivide_cuts, use_grid_fill=True)
    bmesh.ops.triangulate(bm, faces=list(bm.faces))

    vertices = []
    faces = []
    for f in bm.faces:
        poly = [v.co.copy() for v in f.verts]
        for dist_fn in distances:
            poly = _clip_polygon(poly, dist_fn)
            if not poly:
                break
        if len(poly) >= 3:
            start = len(vertices)
            vertices.extend(poly)
            faces.append(tuple(range(start, start + len(poly))))
    bm.free()

    if not faces:
        raise RuntimeError(f"Empty clipped garment surface for {name}")

    mesh = bpy.data.meshes.new(name)
    mesh.from_pydata(vertices, [], faces)
    bm = bmesh.new()
    bm.from_mesh(mesh)
    bmesh.ops.remove_doubles(bm, verts=list(bm.verts), dist=0.0008)
    bmesh.ops.dissolve_degenerate(bm, edges=list(bm.edges), dist=0.0005)
    bmesh.ops.triangulate(bm, faces=list(bm.faces))
    _orient_mesh_islands_outward(bm)
    bm.normal_update()

    if bridge_bust:
        _bridge_cleavage_bmesh(bm)
        bm.normal_update()

    for v in bm.verts:
        v.co += v.normal * clearance

    uv_layer = bm.loops.layers.uv.new("UVMap")
    for f in bm.faces:
        f.smooth = True
        if mat_index_fn is not None:
            f.material_index = mat_index_fn(f)
        for loop in f.loops:
            p = loop.vert.co
            ang = math.atan2(p.y, p.x)
            loop[uv_layer].uv = ((ang / (2.0 * math.pi) + 0.5) * uv_scale[0], p.z * uv_scale[1])

    bm.verts.index_update()
    pin_indices = set()
    for v in bm.verts:
        if pin_boundary and v.is_boundary:
            pin_indices.add(v.index)
        elif pin_predicate is not None and pin_predicate(v.co):
            pin_indices.add(v.index)

    bm.to_mesh(mesh)
    bm.free()

    obj = bpy.data.objects.new(name, mesh)
    bpy.context.scene.collection.objects.link(obj)
    for m in materials:
        obj.data.materials.append(m)
    return obj, pin_indices


def fit_cloth_sim(
    obj: bpy.types.Object,
    pin_indices: set[int],
    *,
    frames: int = 16,
    mass: float = 0.16,
    tension: float = 34.0,
    compression: float = 34.0,
    shear: float = 16.0,
    bending: float = 0.8,
    gravity: float = 0.0,
    air_damping: float = 1.4,
    dist_min: float = 0.0022,
    self_dist_min: float = 0.0016,
    shrink_min: float = 0.0,
):
    """Run real Blender Cloth simulation with collisions and self-collisions, then bake to mesh."""
    if pin_indices:
        vg = obj.vertex_groups.new(name="ClothPin")
        vg.add(sorted(pin_indices), 1.0, "REPLACE")

    cloth = obj.modifiers.new("BasiquesCloth", "CLOTH")
    if pin_indices:
        cloth.settings.vertex_group_mass = "ClothPin"
    cloth.settings.quality = 8
    cloth.settings.mass = mass
    cloth.settings.tension_stiffness = tension
    cloth.settings.compression_stiffness = compression
    cloth.settings.shear_stiffness = shear
    cloth.settings.bending_stiffness = bending
    cloth.settings.air_damping = air_damping
    cloth.settings.shrink_min = shrink_min
    cloth.settings.effector_weights.gravity = gravity
    cloth.collision_settings.use_collision = True
    cloth.collision_settings.distance_min = dist_min
    cloth.collision_settings.use_self_collision = True
    cloth.collision_settings.self_distance_min = self_dist_min
    cloth.point_cache.frame_start = 1
    cloth.point_cache.frame_end = frames

    bpy.context.scene.frame_set(1)
    before = [v.co.copy() for v in obj.data.vertices]
    for frame in range(1, frames + 1):
        bpy.context.scene.frame_set(frame)
        ev = obj.evaluated_get(bpy.context.evaluated_depsgraph_get())
        ev.to_mesh()
        ev.to_mesh_clear()

    bpy.context.view_layer.objects.active = obj
    obj.select_set(True)
    bpy.ops.object.modifier_apply(modifier=cloth.name)
    if not all(math.isfinite(c) for v in obj.data.vertices for c in v.co):
        raise RuntimeError(f"{obj.name}: non-finite Cloth output")
    motion = max((v.co - p).length for v, p in zip(obj.data.vertices, before))
    print(f"{obj.name}: Cloth {frames} frames, max motion {motion:.5f} m", flush=True)
    obj.vertex_groups.clear()
    bpy.context.scene.frame_set(1)
    return motion


