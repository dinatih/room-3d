def append_tube_along_points(
    bm: bmesh.types.BMesh,
    pts: list[Vector],
    radius: float | list[float],
    n_seg: int = 8,
    mat_idx: int = 0,
    cap_ends: bool = True,
):
    """Sweep a smooth circular tube along a 3D polyline."""
    if len(pts) < 2:
        return []
    rings = []
    for i, p in enumerate(pts):
        if i == 0:
            tang = (pts[1] - pts[0]).normalized()
        elif i == len(pts) - 1:
            tang = (pts[-1] - pts[-2]).normalized()
        else:
            tang = (pts[i + 1] - pts[i - 1]).normalized()
        up_ref = Vector((0.0, 0.0, 1.0)) if abs(tang.z) < 0.85 else Vector((1.0, 0.0, 0.0))
        b1 = tang.cross(up_ref).normalized()
        b2 = tang.cross(b1).normalized()
        r = radius[i] if isinstance(radius, list) else radius
        ring = []
        for k in range(n_seg):
            a = (k / n_seg) * 2.0 * math.pi
            ring.append(bm.verts.new(p + (b1 * math.cos(a) + b2 * math.sin(a)) * r))
        rings.append(ring)

    faces = []
    for i in range(len(rings) - 1):
        for k in range(n_seg):
            kn = (k + 1) % n_seg
            f = bm.faces.new((rings[i][k], rings[i][kn], rings[i + 1][kn], rings[i + 1][k]))
            f.material_index = mat_idx
            faces.append(f)
    if cap_ends:
        f0 = bm.faces.new(list(reversed(rings[0])))
        f1 = bm.faces.new(rings[-1])
        f0.material_index = mat_idx
        f1.material_index = mat_idx
        faces.extend([f0, f1])
    return faces


def build_ribbon_strap_object(
    name: str,
    pts: list[Vector],
    bvh_torso: BVHTree,
    half_width: float,
    thickness: float,
    clearance: float,
    material,
):
    """Build a flat contoured fabric strap along a 3D curve hugging the torso."""
    bm = bmesh.new()
    uv_layer = bm.loops.layers.uv.new("UVMap")
    n_w = 4
    rows_o = []
    rows_i = []
    for i, base in enumerate(pts):
        tang = (pts[min(len(pts) - 1, i + 1)] - pts[max(0, i - 1)]).normalized()
        loc, nrm, _, _ = bvh_torso.find_nearest(base)
        out_n = nrm.normalized() if loc is not None else Vector((0.0, 0.0, 1.0))
        lat = tang.cross(out_n)
        if lat.length < 1e-5:
            lat = Vector((1.0, 0.0, 0.0))
        lat.normalize()

        ro = []
        ri = []
        for wi in range(n_w):
            u = ((wi / (n_w - 1)) - 0.5) * 2.0
            probe = base + lat * (u * half_width)
            p_o = ensure_3d_surface_clearance(probe, bvh_torso, clearance, max_dist=0.05)
            p_i = p_o - out_n * thickness
            ro.append(bm.verts.new(p_o))
            ri.append(bm.verts.new(p_i))
        rows_o.append(ro)
        rows_i.append(ri)

    for i in range(len(pts) - 1):
        for wi in range(n_w - 1):
            bm.faces.new((rows_o[i][wi], rows_o[i][wi + 1], rows_o[i + 1][wi + 1], rows_o[i + 1][wi]))
            bm.faces.new((rows_i[i][wi], rows_i[i + 1][wi], rows_i[i + 1][wi + 1], rows_i[i][wi + 1]))
        bm.faces.new((rows_o[i][0], rows_i[i][0], rows_i[i + 1][0], rows_o[i + 1][0]))
        bm.faces.new((rows_o[i][-1], rows_o[i + 1][-1], rows_i[i + 1][-1], rows_i[i][-1]))
    for wi in range(n_w - 1):
        bm.faces.new((rows_o[0][wi], rows_i[0][wi], rows_i[0][wi + 1], rows_o[0][wi + 1]))
        bm.faces.new((rows_o[-1][wi], rows_o[-1][wi + 1], rows_i[-1][wi + 1], rows_i[-1][wi]))

    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    for f in bm.faces:
        f.smooth = True
        for loop in f.loops:
            p = loop.vert.co
            loop[uv_layer].uv = (p.x * 6.0, p.z * 6.0)

    mesh = bpy.data.meshes.new(name)
    bm.to_mesh(mesh)
    bm.free()
    obj = bpy.data.objects.new(name, mesh)
    bpy.context.scene.collection.objects.link(obj)
    obj.data.materials.append(material)
    return obj


def build_knot_bow_object(
    name: str,
    anchor: Vector,
    out_dir: Vector,
    tangent_dir: Vector,
    down_dir: Vector,
    material,
    scale: float = 1.0,
):
    """Build a crisp 3D tie knot with two bow loops and two dangling ribbon tails."""
    bm = bmesh.new()
    uv_layer = bm.loops.layers.uv.new("UVMap")
    out_n = out_dir.normalized()
    tan_n = tangent_dir.normalized()
    dn_n = down_dir.normalized()

    # Center knot
    res = bmesh.ops.create_icosphere(bm, subdivisions=1, radius=0.0052 * scale)
    for v in res["verts"]:
        v.co = anchor + out_n * (0.004 * scale) + Vector((v.co.x, v.co.y * 0.7, v.co.z))

    # Two bow loops
    for side in (-1.0, 1.0):
        loop_pts = []
        for i in range(11):
            a = (i / 10.0) * 2.0 * math.pi
            lx = side * (0.015 * scale) * (0.5 - 0.5 * math.cos(a))
            lz = (0.007 * scale) * math.sin(a)
            ly = (0.004 * scale) * math.sin(a * 0.5)
            loop_pts.append(anchor + tan_n * lx - dn_n * lz + out_n * (0.004 * scale + ly))
        append_tube_along_points(bm, loop_pts, 0.0022 * scale, n_seg=6, cap_ends=False)

    # Two dangling tie tails
    for side in (-1.0, 1.0):
        tail_pts = []
        for i in range(8):
            t = i / 7.0
            tail_pts.append(
                anchor
                + tan_n * (side * (0.004 + 0.014 * t) * scale)
                + dn_n * ((0.038 * t) * scale)
                + out_n * ((0.005 + 0.004 * math.sin(t * math.pi)) * scale)
            )
        append_tube_along_points(bm, tail_pts, 0.0020 * scale, n_seg=6, cap_ends=True)

    bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
    for f in bm.faces:
        f.smooth = True
        for loop in f.loops:
            p = loop.vert.co
            loop[uv_layer].uv = (p.x * 12.0, p.z * 12.0)

    mesh = bpy.data.meshes.new(name)
    bm.to_mesh(mesh)
    bm.free()
    obj = bpy.data.objects.new(name, mesh)
    bpy.context.scene.collection.objects.link(obj)
    obj.data.materials.append(material)
    return obj


